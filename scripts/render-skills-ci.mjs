#!/usr/bin/env node
// render-skills-ci.mjs — derive .github/workflows/skills-ci.yml from skills/.github/workflows/ci.yml
// (public-monorepo S1.2, D3).
//
//   node scripts/render-skills-ci.mjs          write the root workflow
//   node scripts/render-skills-ci.mjs --check  exit 1 if the committed workflow is not what this renders
//
// Why a root copy at all: GitHub only runs workflows from the ROOT .github/, so skills/.github/workflows/ci.yml
// is inert here — it runs in the golden-frijoles/skills mirror, after a change has already reached it. The root job
// gates a PR BEFORE the mirror sees it.
//
// Why it runs on the SPLIT, not the prefix: 20 skills scripts read git (check-release, doc-format, build-state…).
// From the monorepo they would see `skills/plugins/…` paths and misclassify them. The job runs
// `git subtree split --prefix=skills` into a worktree — byte-for-byte what the mirror will hold — and runs the
// skills steps there.
//
// Why derived, not hand-copied: two hand-kept copies of 22 steps drift. The steps are taken verbatim from the
// skills file; only the lines that name the checkout are rewritten, and each rewrite must hit exactly the number
// of lines it expects — a new step that needs a rewrite fails the render instead of silently running wrong.
//
// Zero deps — Node 18+.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const SOURCE = 'skills/.github/workflows/ci.yml';
export const TARGET = '.github/workflows/skills-ci.yml';

/** The lines that name the checkout, and how many times each must appear in the skills steps. */
export const REWRITES = [
  { from: '--base "origin/$BASE_REF"', to: '--base "$MIRROR_BASE"', count: 1 },
  { from: '"$GITHUB_WORKSPACE/', to: '"$MIRROR/', count: 3 },
];

const HEADER = `# GENERATED by scripts/render-skills-ci.mjs from ${SOURCE} — do not edit by hand.
# Regenerate: node scripts/render-skills-ci.mjs  ·  CI fails when this file and its source disagree.
#
# The skills CI, run on \`git subtree split --prefix=skills\` (public-monorepo D3): exactly the tree the
# golden-frijoles/skills mirror receives, so git-reading scripts see mirror-relative paths.
name: Skills CI

on:
  pull_request:
    paths:
      - 'skills/**'
      - '.github/workflows/skills-ci.yml'
      - 'scripts/render-skills-ci.mjs'

permissions:
  contents: read

concurrency:
  group: skills-ci-\${{ github.ref }}
  cancel-in-progress: true

jobs:
  checks:
    runs-on: ubuntu-latest
    env:
      MIRROR: \${{ github.workspace }}/../skills-mirror
    defaults:
      run:
        working-directory: \${{ github.workspace }}/../skills-mirror
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0 # the split needs full history

      - uses: actions/setup-node@v4
        with:
          node-version: '20'

      - name: This workflow matches its source
        working-directory: \${{ github.workspace }}
        run: node scripts/render-skills-ci.mjs --check

      # The mirror tree for this PR, and the base to diff it against. Before skills/ existed on the base branch
      # (the PR that added it), the equivalent base is the mirror repo's own main.
      - name: Split skills/ into the mirror tree
        working-directory: \${{ github.workspace }}
        env:
          BASE_REF: \${{ github.base_ref }}
        run: |
          git config user.name ci && git config user.email ci@localhost
          head=$(git subtree split --prefix=skills HEAD)
          git worktree add --detach "$MIRROR" "$head"
          if git cat-file -e "origin/$BASE_REF:skills" 2>/dev/null; then
            base=$(git subtree split --prefix=skills "origin/$BASE_REF")
          else
            git fetch --quiet https://github.com/golden-frijoles/skills.git main
            base=$(git rev-parse FETCH_HEAD)
          fi
          echo "MIRROR_BASE=$base" >> "$GITHUB_ENV"
          echo "mirror tree: $head · base: $base"

`;

/** The skills job's steps AFTER its own checkout + setup-node (which the header replaces). Pure. */
export function stepsBody(source) {
  const marker = /\n {6}- uses: actions\/setup-node@v4\n {8}with:\n {10}node-version: '20'\n/;
  const m = source.match(marker);
  if (!m) throw new Error(`${SOURCE}: could not find its setup-node step — the render needs updating`);
  return source.slice(m.index + m[0].length).replace(/^\n+/, '');
}

/** Render the root workflow from the skills workflow text. Pure; throws when a rewrite count is off. */
export function render(source) {
  let body = stepsBody(source);
  for (const { from, to, count } of REWRITES) {
    const seen = body.split(from).length - 1;
    if (seen !== count)
      throw new Error(`${SOURCE}: expected ${count} × ${JSON.stringify(from)}, found ${seen} — update REWRITES`);
    body = body.split(from).join(to);
  }
  const stray = body.match(/\$GITHUB_WORKSPACE|origin\/\$BASE_REF/);
  if (stray) throw new Error(`${SOURCE}: an unrewritten checkout reference remains (${stray[0]})`);
  return HEADER + body;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const out = render(readFileSync(join(ROOT, SOURCE), 'utf8'));
  if (process.argv.includes('--check')) {
    let committed = '';
    try {
      committed = readFileSync(join(ROOT, TARGET), 'utf8');
    } catch {}
    if (committed !== out) {
      console.error(`${TARGET} is stale — run: node scripts/render-skills-ci.mjs`);
      process.exit(1);
    }
    console.log(`${TARGET} matches ${SOURCE}.`);
  } else {
    writeFileSync(join(ROOT, TARGET), out);
    console.log(`wrote ${TARGET} from ${SOURCE}.`);
  }
}
